"""Блокировки «один пользователь — одна проверка лимита за раз» (аудит C06).

Суточные лимиты (дистанция и число забегов, число захватов) проверяются так:
посчитать, что уже есть, сравнить с потолком, записать новое. Без блокировки два
параллельных запроса одного человека оба видят «ещё не упёрлись» и оба проходят —
потолок превышается ровно на число одновременных запросов. Для захвата хуже:
оба запроса читают площадь следа «до», и новая земля оплачивается дважды.

Решение — транзакционная advisory-блокировка PostgreSQL на пару
(пространство, пользователь). Держится до конца текущей транзакции, поэтому
вызывать ТОЛЬКО внутри `transaction.atomic()`: проверка лимита и запись идут
под одной блокировкой, второй запрос того же человека ждёт, пока первый
закоммитится, и уже видит его запись. Другие пользователи не ждут.
"""
from django.db import connection

# Пространства блокировок (первый аргумент pg_advisory_xact_lock). Свои забеги и
# импорт с часов делят один суточный бюджет дистанции — поэтому одно пространство.
ACTIVITY = 60601    # POST /v1/runs, POST /v1/workouts/import
TERRITORY = 60602   # POST /v1/territories/capture


def lock_user(namespace: int, uid: str) -> None:
    """Взять блокировку (namespace, uid) до конца текущей транзакции."""
    if not connection.in_atomic_block:
        raise RuntimeError("lock_user вызывается только внутри transaction.atomic()")
    with connection.cursor() as cur:
        cur.execute(
            "SELECT pg_advisory_xact_lock(%s, hashtext(%s))", [namespace, str(uid)]
        )
