"""Пороги анти-чита и цена километра (S-04) — в одном месте.

Раньше эти числа жили в `runs/views.py`, и всё, что хотело их узнать (модерация,
тренировки с часов), тянуло за собой весь модуль представлений. Теперь правила
лежат отдельно: приём забега, разбор помеченных и импорт тренировок читают одни
и те же значения, а менять их нужно ровно здесь.
"""
from datetime import timedelta

# Скорость согласована с territories (40 км/ч).
MAX_SPEED_MS = 11.2            # ~40 км/ч — серверный потолок (как в territories)
MAX_RUN_DISTANCE_M = 100_000   # 100 км за один забег — неправдоподобно
MAX_DAY_DISTANCE_M = 150_000   # 150 км/сутки суммарно — щедрый потолок против фарма
MAX_RUNS_PER_DAY = 30          # >30 забегов/сутки — спам/автоматизация (для человека много)
POINTS_PER_KM = 10             # очки = км × 10 (как было на клиенте, теперь на сервере)
FUTURE_SKEW = timedelta(hours=12)   # допуск на часовые пояса/рассинхрон часов
MAX_RUN_AGE = timedelta(days=30)    # старше — подозрение на реплей/бэкфилл фейков

# Суточный потолок БАЛЛОВ за активность (решение владельца 28.09.2026): свои
# забеги + импорт тренировок с часов + захваты территорий — вместе не больше
# стольких баллов за сутки. Сутки — календарный день UTC по времени начисления
# (как и прочие суточные лимиты). Сверх потолка начисляется 0 с причиной в ответе
# (не 400: забег/тренировка/захват засчитываются, просто без баллов).
# Вехи, дивизион и сезон сюда не входят: они разовые и ограничены сами по себе.
MAX_DAY_ACTIVITY_POINTS = 1000
DAY_CAP_SOURCES = ("runnerRun", "runnerTerritory")
DAY_CAP_REASON = (
    f"Достигнут суточный потолок: не больше {MAX_DAY_ACTIVITY_POINTS} баллов "
    "за бег и захваты в сутки"
)

# Режим доверия (S-04): при накоплении флагнутых забегов помечаем аккаунт «на ревью».
REVIEW_FLAGGED_THRESHOLD = 5        # столько флагов за окно → отметка модератору
REVIEW_WINDOW = timedelta(days=7)


def points_for(distance_m: float) -> int:
    """Сколько баллов стоит забег такой длины. Одна формула на весь проект."""
    return round(distance_m / 1000.0 * POINTS_PER_KM)
