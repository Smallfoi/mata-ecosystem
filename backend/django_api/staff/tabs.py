BY_KEY = {t.key: t for t in TABS}


def groups():
    """Вкладки, сгруппированные как в меню — для формы прав."""
    out = []
    for tab in TABS:
        if not out or out[-1][0] != tab.group:
            out.append((tab.group, []))
        out[-1][1].append(tab)
    return out
